/**
 * Vitest test — generates the seed.ts and seed-mini.ts fixtures from
 * the real Doorstop YAMLs. Opt-in via the GENERATE_FIXTURES env var:
 *
 *   GENERATE_FIXTURES=1 pnpm vitest run tests/unit/rem/fixtures/_generate.test.ts
 *
 * The generated `seed.ts` and `seed-mini.ts` are committed; this test
 * just (re)writes them when the env var is set. The test asserts the
 * expected counts (48 RF + 30 RNF + 3 stakeholders) to catch any drift
 * after a migration run.
 */

import { describe, it, expect } from "vitest";
import { writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

import { loadAllRequirements, clearLoaderCache } from "../../../../src/lib/rem/loader";
import type {
  RemDataset,
  Requirement,
  Stakeholder,
} from "../../../../src/lib/rem/types";

const HERE = resolve(__dirname);
const REAL_REQ = resolve(HERE, "../../../../../scripts/requirements/req");

function toModule(dataset: RemDataset, varName: string): string {
  const rf = dataset.rf.map(serialiseReq).join(",\n  ");
  const rnf = dataset.rnf.map(serialiseReq).join(",\n  ");
  const stk = dataset.stakeholders.map(serialiseStk).join(",\n  ");
  return [
    "/* eslint-disable */",
    "// AUTO-GENERATED by _generate.test.ts — do not edit by hand.",
    "// Re-run after `python scripts/requirements/migrate_to_doorstop.py`.",
    "",
    "import type { RemDataset } from \"../../../../src/lib/rem/types\";",
    "",
    `export const ${varName}: RemDataset = {`,
    "  rf: [",
    `  ${rf}`,
    "  ],",
    "  rnf: [",
    `  ${rnf}`,
    "  ],",
    "  stakeholders: [",
    `  ${stk}`,
    "  ],",
    "};",
    "",
  ].join("\n");
}

function serialiseReq(r: Requirement): string {
  return JSON.stringify(r, null, 2).replace(/\n/g, "\n  ");
}

function serialiseStk(s: Stakeholder): string {
  return JSON.stringify(s, null, 2).replace(/\n/g, "\n  ");
}

const SHOULD_GENERATE = process.env.GENERATE_FIXTURES === "1";

describe("_generate (opt-in: GENERATE_FIXTURES=1)", () => {
  it.skipIf(!SHOULD_GENERATE)(
    "writes seed.ts and seed-mini.ts from the real Doorstop folder",
    () => {
      if (!existsSync(REAL_REQ)) {
        throw new Error(`Real Doorstop folder missing: ${REAL_REQ}`);
      }
      clearLoaderCache();
      const dataset = loadAllRequirements();
      writeFileSync(resolve(HERE, "seed.ts"), toModule(dataset, "SEED_DATASET"));
      const mini: RemDataset = {
        rf: dataset.rf.slice(0, 3),
        rnf: dataset.rnf.slice(0, 2),
        stakeholders: dataset.stakeholders.slice(0, 1),
      };
      writeFileSync(resolve(HERE, "seed-mini.ts"), toModule(mini, "SEED_MINI"));
      expect(dataset.rf.length).toBe(48);
      expect(dataset.rnf.length).toBe(30);
      expect(dataset.stakeholders.length).toBe(3);
    },
  );
});
